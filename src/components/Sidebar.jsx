export default function Sidebar({ theme, toggleTheme, isOpen, onToggle }) {
  const location = useLocation();

  return (
    <aside className={`sidebar ${isOpen ? 'sidebar-open' : 'sidebar-collapsed'}`}>
      {/* Brand */}
      <div className="sidebar-brand">
        <div className="brand-icon"><Icon name="buffalo" /></div>
        {isOpen && (
          <div className="brand-text">
            <h1>Cowculator</h1>
            <span>Shash Farm</span>
          </div>
        )}
      </div>

      {/* Navigation */}
      <nav className="sidebar-nav">
        {navItems.map(item => (
          <NavLink
            key={item.path}
            to={item.path}
            className={({ isActive }) => `nav-item ${isActive ? 'nav-item-active' : ''}`}
            end={item.path === '/'}
          >
            <span className="nav-icon"><Icon name={item.icon} /></span>
            {isOpen && <span className="nav-label">{item.label}</span>}
            {location.pathname === item.path && <div className="nav-indicator" />}
          </NavLink>
        ))}
      </nav>

      {/* Bottom Actions */}
      <div className="sidebar-footer">
        <button className="sidebar-btn" onClick={toggleTheme} title={theme === 'dark' ? 'Light Mode' : 'Dark Mode'}>
          <span className="nav-icon"><Icon name={theme === 'dark' ? 'sun' : 'moon'} /></span>
          {isOpen && <span className="nav-label">{theme === 'dark' ? 'Light Mode' : 'Dark Mode'}</span>}
        </button>
        <button className="sidebar-btn" onClick={onToggle} title="Toggle Sidebar">
          <span className="nav-icon"><Icon name={isOpen ? 'collapse' : 'expand'} /></span>
          {isOpen && <span className="nav-label">{isOpen ? 'Collapse' : 'Expand'}</span>}
        </button>
      </div>
    </aside>
  );
}
